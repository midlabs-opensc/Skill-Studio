const pythonSnippets = [
  { label: "print", insertText: "print(${1:value})" },
  {
    label: "property",
    insertText: "@property\ndef ${1:name}(self):\n\treturn ${2:value}",
  },
  { label: "def", insertText: "def ${1:name}(${2:args}):\n\t${0:pass}" },
  {
    label: "class",
    insertText:
      "class ${1:Name}:\n\tdef __init__(self${2:, args}):\n\t\t${0:pass}",
  },
  { label: "ifmain", insertText: 'if __name__ == "__main__":\n\t${0:main()}' },
];

for (const [language, words] of Object.entries(languageKeywords)) {
  monaco.languages.registerCompletionItemProvider(language, {
    provideCompletionItems(model, position) {
      const word = model.getWordUntilPosition(position);
      const range = {
        startLineNumber: position.lineNumber,
        endLineNumber: position.lineNumber,
        startColumn: word.startColumn,
        endColumn: word.endColumn,
      };
      const suggestions: monaco.languages.CompletionItem[] = words.map(
        (label) => ({
          label,
          insertText: label,
          kind: monaco.languages.CompletionItemKind.Keyword,
          range,
        }),
      );
      if (language === "python") {
        suggestions.push(
          ...pythonSnippets.map((item) => ({
            ...item,
            kind: monaco.languages.CompletionItemKind.Snippet,
            insertTextRules:
              monaco.languages.CompletionItemInsertTextRule.InsertAsSnippet,
            range,
          })),
        );
      }
      return { suggestions };
    },
  });
}
